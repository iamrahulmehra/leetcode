class Solution {
    public long countCommas(long n) {
        if(n<1000){
            return 0;
        }
        else if(n<1000000){
            return n-999;
        }
        else if(n<1000000000){
            return (n -999999)*2 +(999999-999);
        }
        else if(n<1000000000000L){
            return (n -999999999)*3 +(999999999-999999)*2 + (999999-999);
        }
        else if(n<1000000000000000L){
            return (n -999999999999L)*4 +(999999999999L-999999999)*3 +(999999999-999999)*2 + (999999-999);
        }
        else{
            return (n -999999999999999L)*5 +(999999999999999L-999999999999L)*4 +(999999999999L-999999999)*3+ (999999999-999999)*2 + (999999-999);
        }
    }
}